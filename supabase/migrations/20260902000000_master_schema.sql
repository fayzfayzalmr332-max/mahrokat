-- 3.1) ختم updated_at تلقائياً
create or replace function public.fn_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

-- 3.2) لمس last_activity_at عند إدراج حركة نقدية
create or replace function public.fn_touch_last_activity()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    update public.customers c
       set last_activity_at = greatest(c.last_activity_at, new.created_at)
     where c.id = new.customer_id
       and (c.last_activity_at is null or c.last_activity_at < new.created_at);
    return new;
end;
$$;

-- 3.3) إعادة حساب last_activity_at بعد حذف حركة نقدية (دقة /undo)
create or replace function public.fn_recalc_last_activity()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    update public.customers c
       set last_activity_at = (
           select max(t.created_at)
             from public.transactions t
            where t.customer_id = c.id
       )
     where c.id = old.customer_id;
    return old;
end;
$$;

-- 3.4) سجل التدقيق المظلم
create or replace function public.fn_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_new jsonb := null;
    v_old jsonb := null;
    v_id  uuid  := null;
begin
    if tg_op in ('INSERT', 'UPDATE') then
        v_new := to_jsonb(new);
        v_id  := new.id;
    end if;

    if tg_op in ('UPDATE', 'DELETE') then
        v_old := to_jsonb(old);
        if tg_op = 'DELETE' then
            v_id := old.id;
        end if;
    end if;

    insert into public.audit_log (table_name, operation, record_id, old_data, new_data, done_by)
    values (tg_table_name, tg_op, v_id, v_old, v_new, session_user::text);

    return coalesce(new, old);
end;
$$;

-- 3.5) RPC: رصيد عميل واحد (PostgREST)
create or replace function public.fn_customer_balance(p_customer_id uuid)
returns numeric(15, 2)
language sql
stable
parallel safe
set search_path = ''
as $$
    select coalesce(sum(t.amount), 0)::numeric(15, 2)
      from public.transactions t
     where t.customer_id = p_customer_id;
$$;


