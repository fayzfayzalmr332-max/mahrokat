-- 6.1) دفتر الأستاذ التراكمي: حركات كل عميل بالترتيب الزمني الحاسم
--      (created_at, seq) مع الرصيد التراكمي بعد كل حركة — numeric(15,2)
drop view if exists public.v_customer_ledger;
create or replace view public.v_customer_ledger as
select
    t.customer_id,
    t.id,
    t.amount,
    t.tx_type,
    t.note,
    t.created_at,
    t.seq,
    sum(t.amount) over (
        partition by t.customer_id
        order by t.created_at, t.seq
        rows between unbounded preceding and current row
    )::numeric(15, 2) as running_balance
from public.transactions t;

comment on view public.v_customer_ledger
    is 'دفتر الأستاذ: حركات كل عميل بالترتيب الزمني الحاسم (created_at, seq) مع الرصيد التراكمي بعد كل حركة';

-- 6.2) الأرصدة النقدية الحية للعملاء
drop view if exists public.v_customer_balances;
create or replace view public.v_customer_balances as
select
    c.id,
    c.name,
    c.name_normalized,
    coalesce(sum(t.amount), 0)::numeric(15, 2) as balance,
    count(t.id)::bigint                          as txn_count,
    max(t.created_at)                            as last_txn_at,
    c.last_activity_at,
    c.created_at,
    c.updated_at,
    case
        when coalesce(sum(t.amount), 0) > 0 then 'debtor'
        when coalesce(sum(t.amount), 0) < 0 then 'creditor'
        else 'settled'
    end as status
from public.customers c
left join public.transactions t on t.customer_id = c.id
group by
    c.id, c.name, c.name_normalized,
    c.last_activity_at, c.created_at, c.updated_at
order by c.name;

comment on view public.v_customer_balances
    is 'الأرصدة الحية للعملاء: debtor (مدين) / creditor (دائن) / settled (مسدَّد)';

-- 6.3) الملخص اليومي للحركات النقدية
drop view if exists public.v_daily_summary;
create view public.v_daily_summary as
select
    date_trunc('day', created_at)::date as day,
    count(*)::bigint                     as txn_count,
    count(*) filter (where tx_type = 'debit')::bigint  as debit_count,
    coalesce(sum(amount) filter (where tx_type = 'debit'), 0)::numeric(15, 2) as debit_total,
    count(*) filter (where tx_type = 'credit')::bigint as credit_count,
    coalesce(sum(-amount) filter (where tx_type = 'credit'), 0)::numeric(15, 2) as credit_total,
    coalesce(sum(amount), 0)::numeric(15, 2) as net_change
from public.transactions
group by 1
order by 1 desc;

-- 6.4) إجماليات النظام
drop view if exists public.v_financial_totals;
create view public.v_financial_totals as
select
    (select count(*)::bigint from public.customers) as customers,
    (select count(*)::bigint from public.transactions) as transactions,
    (select coalesce(sum(amount), 0)::numeric(15, 2) from public.transactions) as total_balance,
    (select coalesce(sum(amount), 0)::numeric(15, 2) from public.transactions where amount > 0) as total_debts,
    (select coalesce(sum(-amount), 0)::numeric(15, 2) from public.transactions where amount < 0) as total_paid,
    (select coalesce(sum(case when entry_type = 'income' then amount else -amount end), 0)::numeric(15, 2)
       from public.account_entries) as account_balance;


-- 6.5) إجماليات الصندوق المحاسبي الشخصي — طلب واحد بدل جلب كل القيود
drop view if exists public.v_account_totals;
create view public.v_account_totals as
select
    coalesce(sum(amount) filter (where entry_type = 'income'), 0)::numeric(15, 2)  as income_total,
    coalesce(sum(amount) filter (where entry_type = 'expense'), 0)::numeric(15, 2) as expense_total,
    coalesce(sum(case when entry_type = 'income' then amount else -amount end), 0)::numeric(15,2) as balance
from public.account_entries;

comment on view public.v_account_totals
    is 'إجماليات الصندوق الشخصي في طلب واحد: دخل / مصروف / الرصيد الصافي';

-- 6.6) أرصدة وقود العملاء — معزولة تماماً عن الأرصدة النقدية
drop view if exists public.v_fuel_balances;
create or replace view public.v_fuel_balances as
select
    c.id,
    c.name,
    c.name_normalized,
    coalesce(sum(f.liters) filter (where f.fuel_type = 'mazot'), 0)::numeric(15, 3)   as mazot_balance,
    coalesce(sum(f.liters) filter (where f.fuel_type = 'benzine'), 0)::numeric(15, 3) as benzine_balance,
    count(f.id)::integer as fuel_txn_count,
    max(f.created_at) as last_fuel_at
from public.customers c
left join public.fuel_ledger f on f.customer_id = c.id
group by c.id, c.name, c.name_normalized
order by c.name;

comment on view public.v_fuel_balances
    is 'أرصدة وقود العملاء معزولة تماماً: مازوت/بنزين باللترات — منفصلة عن v_customer_balances النقدية';

