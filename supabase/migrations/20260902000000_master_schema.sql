-- ── 1.2) حركات النقد (الديون والسداديات) ─────────────────────────
create table if not exists public.transactions (
    id           uuid primary key default gen_random_uuid(),
    customer_id  uuid not null
        references public.customers (id) on delete restrict,
    amount       numeric(15,2) not null check (amount <> 0),
    tx_type      text not null check (tx_type in ('debit', 'credit')),
    note         text,
    external_ref text,
    seq          bigint generated by default as identity,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    -- القيد الذهبي: الإشارة تطابق الاتجاه دائماً
    constraint ck_transactions_sign check (
        (tx_type = 'debit'  and amount > 0)
     or (tx_type = 'credit' and amount < 0)
    ),
    -- منع تسجيل الحركة مرتين ذرّياً (Idempotency)
    constraint ux_transactions_external_ref unique (external_ref),
    constraint ck_transactions_note_len check (note is null or char_length(note) <= 500)
);

